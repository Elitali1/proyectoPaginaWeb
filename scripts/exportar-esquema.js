// scripts/exportar-esquema.js
//
// Genera la migración inicial (el "esquema actual") leyendo la estructura de una base PostgreSQL.
//
// ES DE SOLO LECTURA: corre todo dentro de una transacción READ ONLY, así que aunque se apunte
// por error a la base de producción no puede modificar nada.
//
// Uso (PowerShell), apuntando a la branch de staging:
//   $env:DATABASE_URL = "postgresql://..."
//   node scripts/exportar-esquema.js
//
// Resultado: migrations/<timestamp>_esquema-inicial.sql (formato de node-pg-migrate).
// Para que sirva como punto de partida, el esquema se exporta SIN datos.

const fs = require('fs');
const path = require('path');
const { Client } = require('pg');

const url = process.env.DATABASE_URL;
if (!url) {
  console.error('Falta DATABASE_URL. Definila en esta terminal antes de correr el script.');
  process.exit(1);
}

// Neon exige SSL; una base local (localhost) no.
const esLocal = /@(localhost|127\.0\.0\.1)/.test(url);
const client = new Client({
  connectionString: url,
  ssl: esLocal ? false : { rejectUnauthorized: false }
});

// Extensiones comunes que sí se recrean; las demás (propias del proveedor) quedan comentadas.
const EXTENSIONES_PERMITIDAS = ['pgcrypto', 'uuid-ossp', 'citext', 'pg_trgm', 'unaccent', 'hstore'];

async function main() {
  await client.connect();
  await client.query('BEGIN READ ONLY');

  const info = (await client.query('SELECT current_database() AS db, current_user AS usuario')).rows[0];
  const host = new URL(url.replace(/^postgres:/, 'postgresql:')).hostname;
  console.log(`Conectado a la base "${info.db}" (host: ${host})`);

  const avisos = [];
  const salida = [];

  // ---- Extensiones
  const extensiones = (await client.query(
    "SELECT extname FROM pg_extension WHERE extname <> 'plpgsql' ORDER BY extname"
  )).rows.map(r => r.extname);

  for (const nombre of extensiones) {
    if (EXTENSIONES_PERMITIDAS.includes(nombre)) {
      salida.push(`CREATE EXTENSION IF NOT EXISTS "${nombre}";`);
    } else {
      salida.push(`-- Extensión "${nombre}" omitida (propia del proveedor). Descomentar si hiciera falta:`);
      salida.push(`-- CREATE EXTENSION IF NOT EXISTS "${nombre}";`);
    }
  }
  if (extensiones.length) salida.push('');

  // ---- Tipos enumerados (deben existir antes que las tablas)
  const enums = (await client.query(`
    SELECT quote_ident(t.typname) AS nombre,
           array_agg(quote_literal(e.enumlabel) ORDER BY e.enumsortorder) AS valores
    FROM pg_type t
    JOIN pg_enum e ON e.enumtypid = t.oid
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
    GROUP BY t.typname
    ORDER BY t.typname
  `)).rows;

  for (const e of enums) {
    salida.push(`CREATE TYPE ${e.nombre} AS ENUM (${e.valores.join(', ')});`);
  }
  if (enums.length) salida.push('');

  // ---- Tablas
  const tablas = (await client.query(`
    SELECT c.oid, c.relname, quote_ident(c.relname) AS nombre
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname <> 'pgmigrations'
    ORDER BY c.relname
  `)).rows;

  for (const tabla of tablas) {
    const columnas = (await client.query(`
      SELECT quote_ident(a.attname) AS col,
             format_type(a.atttypid, a.atttypmod) AS tipo,
             a.attnotnull AS no_nulo,
             a.attidentity AS identidad,
             a.attgenerated AS generada,
             pg_get_expr(d.adbin, d.adrelid) AS por_defecto,
             pg_get_serial_sequence(quote_ident('public') || '.' || quote_ident($2), a.attname) AS serie
      FROM pg_attribute a
      LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY a.attnum
    `, [tabla.oid, tabla.relname])).rows;

    const lineas = columnas.map(c => {
      const esSerial = c.por_defecto && c.por_defecto.startsWith('nextval(') && c.serie;
      const serialPorTipo = { integer: 'SERIAL', bigint: 'BIGSERIAL', smallint: 'SMALLSERIAL' };

      if (esSerial && serialPorTipo[c.tipo]) {
        return `  ${c.col} ${serialPorTipo[c.tipo]}`;
      }

      let linea = `  ${c.col} ${c.tipo}`;

      if (c.identidad === 'a') linea += ' GENERATED ALWAYS AS IDENTITY';
      else if (c.identidad === 'd') linea += ' GENERATED BY DEFAULT AS IDENTITY';
      else if (c.generada === 's') linea += ` GENERATED ALWAYS AS (${c.por_defecto}) STORED`;
      else if (c.por_defecto) {
        if (c.por_defecto.startsWith('nextval(')) {
          avisos.push(`La columna ${tabla.nombre}.${c.col} usa una secuencia que no le pertenece; revisar a mano.`);
        }
        linea += ` DEFAULT ${c.por_defecto}`;
      }

      if (c.no_nulo && !c.identidad && c.generada !== 's') linea += ' NOT NULL';
      return linea;
    });

    salida.push(`CREATE TABLE ${tabla.nombre} (\n${lineas.join(',\n')}\n);`);
    salida.push('');
  }

  // ---- Restricciones: primero PK / UNIQUE / CHECK, y al final las claves foráneas
  const restricciones = (await client.query(`
    SELECT quote_ident(cl.relname) AS tabla,
           quote_ident(con.conname) AS nombre,
           con.contype AS tipo,
           pg_get_constraintdef(con.oid) AS definicion
    FROM pg_constraint con
    JOIN pg_class cl ON cl.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = cl.relnamespace
    WHERE n.nspname = 'public' AND cl.relname <> 'pgmigrations' AND con.contype IN ('p', 'u', 'c', 'x', 'f')
    ORDER BY CASE con.contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 WHEN 'x' THEN 4 ELSE 5 END,
             cl.relname, con.conname
  `)).rows;

  for (const r of restricciones) {
    salida.push(`ALTER TABLE ${r.tabla} ADD CONSTRAINT ${r.nombre} ${r.definicion};`);
  }
  if (restricciones.length) salida.push('');

  // ---- Índices que no respaldan una restricción
  const indices = (await client.query(`
    SELECT pg_get_indexdef(i.indexrelid) AS definicion
    FROM pg_index i
    JOIN pg_class ic ON ic.oid = i.indexrelid
    JOIN pg_class t ON t.oid = i.indrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname = 'public' AND t.relname <> 'pgmigrations'
      AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid)
    ORDER BY t.relname, ic.relname
  `)).rows;

  for (const i of indices) {
    salida.push(`${i.definicion};`);
  }
  if (indices.length) salida.push('');

  // ---- Cosas que este script NO exporta: se avisa para no perderlas sin darse cuenta
  const noExportado = (await client.query(`
    SELECT
      (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind IN ('v', 'm', 'p')) AS vistas,
      (SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND NOT t.tgisinternal) AS triggers,
      (SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'public'
          AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')) AS funciones
  `)).rows[0];

  if (Number(noExportado.vistas)) avisos.push(`Hay ${noExportado.vistas} vista(s)/tabla(s) particionada(s) que NO se exportaron.`);
  if (Number(noExportado.triggers)) avisos.push(`Hay ${noExportado.triggers} trigger(s) que NO se exportaron.`);
  if (Number(noExportado.funciones)) avisos.push(`Hay ${noExportado.funciones} función(es) que NO se exportaron.`);

  await client.query('ROLLBACK');
  await client.end();

  // ---- Armado del archivo en formato node-pg-migrate
  const fecha = new Date().toISOString().slice(0, 10);
  const contenido = [
    '-- Up Migration',
    '-- ============================================================================',
    `-- ESQUEMA INICIAL de la base "${info.db}" (exportado el ${fecha}).`,
    '-- Solo estructura, sin datos. Sirve para reconstruir la base desde cero.',
    '--',
    '-- En una base que YA tiene estas tablas (por ejemplo producción) NO se ejecuta:',
    '-- se marca como aplicada con  npm run migrate -- up --fake',
    '-- ============================================================================',
    '',
    ...salida,
    '-- Down Migration',
    '-- El esquema inicial no se deshace.',
    ''
  ].join('\n');

  const marca = Date.now();
  const destino = process.argv[2] || path.join('migrations', `${marca}_esquema-inicial.sql`);
  fs.mkdirSync(path.dirname(destino), { recursive: true });
  fs.writeFileSync(destino, contenido, 'utf8');

  console.log(`Tablas: ${tablas.length} | Restricciones: ${restricciones.length} | Índices: ${indices.length}`);
  console.log(`Archivo generado: ${destino}`);
  if (avisos.length) {
    console.log('\nAVISOS (revisar):');
    avisos.forEach(a => console.log(' - ' + a));
  }
}

main().catch(async (error) => {
  console.error('Error:', error.message);
  try { await client.end(); } catch (_) { /* ya cerrada */ }
  process.exit(1);
});